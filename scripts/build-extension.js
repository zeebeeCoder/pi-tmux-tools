// Build only the Pi entry. The CLI/Claude programs continue to use src/ directly.
import { build, version } from 'esbuild';
import { builtinModules } from 'node:module';
import { readFile, writeFile, realpath } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const hosts = ['@earendil-works/pi-coding-agent', '@earendil-works/pi-ai',
  '@earendil-works/pi-agent-core', '@earendil-works/pi-tui', 'typebox'];

export async function buildExtension({ root = repo, check = false } = {}) {
  // esbuild canonicalizes input paths (e.g. macOS /var -> /private/var).
  root = await realpath(root);
  const manifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  if (manifest.devDependencies?.esbuild !== version) {
    throw new Error('Bundler version differs from the exact devDependency pin; run npm ci --legacy-peer-deps.');
  }
  const result = await build({
    absWorkingDir: root, entryPoints: ['src/extension.ts'], outfile: 'extension.ts',
    bundle: true, platform: 'node', format: 'esm', target: 'node22.18',
    external: hosts, write: false, metafile: true, legalComments: 'none',
    plugins: [{
      name: 'source-relative-urls',
      setup(builder) {
        // Bundling moves import.meta.url to the package root. Preserve the source
        // module's URL base (not a JS import), including Python/bin asset paths.
        builder.onLoad({ filter: /\.[jt]s$/ }, async ({ path }) => {
          const source = await readFile(path, 'utf8');
          const sourcePath = './' + relative(root, path).replaceAll('\\', '/');
          return {
            contents: source.replaceAll('import.meta.url',
              `new URL(${JSON.stringify(sourcePath)}, import.meta.url).href`),
            loader: path.endsWith('.ts') ? 'ts' : 'js'
          };
        });
      }
    }]
  });
  // No emitted local JS imports (including dynamic imports) may escape bundling.
  for (const output of Object.values(result.metafile.outputs)) {
    for (const item of output.imports) {
      if (!item.external || !(item.path.startsWith('node:') || builtinModules.includes(item.path) ||
          hosts.some(host => item.path === host || item.path.startsWith(host + '/')))) {
        throw new Error('Unexpected bundle import: ' + item.path);
      }
    }
  }
  // Include even tree-shaken inputs and build logic in freshness, not mtimes.
  const hash = createHash('sha256').update(version).update(await readFile(fileURLToPath(import.meta.url)));
  for (const path of Object.keys(result.metafile.inputs).sort()) {
    hash.update(path).update(await readFile(resolve(root, path)));
  }
  const code = '// @ts-nocheck\n// GENERATED by npm run build; do not edit.\n' +
    `// Source/build SHA256: ${hash.digest('hex')}\n` + result.outputFiles[0].text;
  const target = resolve(root, 'extension.ts');
  if (check) {
    const existing = await readFile(target, 'utf8').catch(() => null);
    if (existing !== code) throw new Error('extension.ts is missing or stale; run npm run build before testing, packaging or /reload.');
  } else {
    await writeFile(target, code);
  }
  return { code, metafile: result.metafile };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildExtension({ check: process.argv.includes('--check') });
  console.error(process.argv.includes('--check') ? 'Pi bundle is fresh.' : 'Built extension.ts.');
}
